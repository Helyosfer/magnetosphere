function t(key, ...args) {
  const value = STRINGS[LANG][key] ?? STRINGS.tr[key];
  if (value === undefined) return key;
  return typeof value === "function" ? value(...args) : value;
}

// panel.html'deki data-i18n* öznitelikleri. Öğenin içinde simge ya da sayaç varsa yalnızca metni değişir.
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  for (const node of root.querySelectorAll("[data-i18n]")) {
    const text = [...node.childNodes].find((n) => n.nodeType === Node.TEXT_NODE && n.data.trim());
    const value = t(node.dataset.i18n);
    if (text) text.data = text.data.replace(text.data.trim(), () => value);
    else node.textContent = value;
  }
  for (const [attr, prop] of [["i18nPlaceholder", "placeholder"], ["i18nTitle", "title"], ["i18nAria", "ariaLabel"]]) {
    for (const node of root.querySelectorAll(`[data-${attr.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}]`)) {
      node[prop] = t(node.dataset[attr]);
    }
  }
}
