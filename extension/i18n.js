const AR_RULES = new Intl.PluralRules("ar");
function arCount(n, [one, two, few, many]) {
  const form = AR_RULES.select(n);
  if (form === "one") return one;
  if (form === "two") return two;
  return `${n} ${form === "few" ? few : many}`;
}
